  accepted=[];tries=0
  while len(accepted)<10:
   tries+=1;black={rng.randrange(n*n)}
   while True:
    cand=list(set(j for i in black for j in neigh(n,i))-black);rng.shuffle(cand);done=False
    for x in cand:
     b=black|{x};r,c=divmod(x,n)
     if any(all(y in b for y in (a*n+d,a*n+d+1,(a+1)*n+d,(a+1)*n+d+1)) for a in [r-1,r] for d in [c-1,c] if 0<=a<n-1 and 0<=d<n-1):continue
