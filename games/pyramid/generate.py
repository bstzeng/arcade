#!/usr/bin/env python3
"""Deterministically construct 50 rank-distinct legal Pyramid deals plus full witnesses.
This is a construction, not a claim that arbitrary shuffled deals are solvable.
"""
import json, random
from pathlib import Path
BASE=Path(__file__).resolve().parent

def build(seed):
    rng=random.Random(seed)
    children=[]
    for r in range(7):
        for c in range(r+1):
            children.append([] if r==6 else [(r+1)*(r+2)//2+c,(r+1)*(r+2)//2+c+1])
    alive=set(range(28)); ranks=[None]*28; pairs=[r for r in range(1,7) for _ in range(4)]; kings=4
    planned=[]; required=[]
    while alive:
        exposed=[i for i in sorted(alive) if all(j not in alive for j in children[i])]
        i=rng.choice(exposed)
        if kings and rng.random()<.15:
            ranks[i]=13; kings-=1; alive.remove(i); planned.append(('king',i)); continue
        if not pairs: return None
        r=pairs.pop(rng.randrange(len(pairs)))
        a,b=(r,13-r) if rng.random()<.5 else (13-r,r)
        ranks[i]=a
        others=[j for j in exposed if j!=i]
        if others and rng.random()<.48:
            j=rng.choice(others); ranks[j]=b; alive.remove(i); alive.remove(j); planned.append(('pair',i,j))
        else:
            if len(required)>=24: return None
            required.append(b); alive.remove(i); planned.append(('stock',i,len(required)-1))
    # Assign all suit/rank IDs without replacement, independently for every rank.
    cardpools={r:[s*13+r-1 for s in range(4)] for r in range(1,14)}
    for p in cardpools.values(): rng.shuffle(p)
    pyramid=[cardpools[r].pop() for r in ranks]
    partners=[cardpools[r].pop() for r in required]
    filler=[c for p in cardpools.values() for c in p]; rng.shuffle(filler)
    # Filler may cover previously exposed waste; required partners preserve proof order.
    slots=[[] for _ in range(len(partners)+1)]
    for c in filler: slots[rng.randrange(len(slots))].append(c)
    stock=[]; offsets=[]
    for n,c in enumerate(partners):
        stock.extend(slots[n]); stock.append(c); offsets.append(len(stock))
    stock.extend(slots[-1]); witness=[]; cursor=0
    for a in planned:
        if a[0]=='king': witness.append({'type':'remove','cards':[pyramid[a[1]]]})
        elif a[0]=='pair': witness.append({'type':'remove','cards':[pyramid[a[1]],pyramid[a[2]]]})
        else:
            while cursor<offsets[a[2]]:
                witness.append({'type':'draw'}); cursor+=1
            witness.append({'type':'remove','cards':[pyramid[a[1]],partners[a[2]]]})
    return {'pyramid':pyramid,'stock':stock,'witness':witness,'seed':seed}

def main():
    deals=[]; seen=set(); seed=730001
    while len(deals)<50:
        d=build(seed); seed+=1
        if d is None: continue
        # Ignore suits, and also collapse a reflected pyramid to the same canonical identity.
        rows=[d['pyramid'][r*(r+1)//2:(r+1)*(r+2)//2] for r in range(7)]
        direct=tuple(c%13+1 for c in d['pyramid']+d['stock'])
        mirror=tuple(c%13+1 for row in rows for c in reversed(row))+tuple(c%13+1 for c in d['stock'])
        canonical=min(direct,mirror)
        if canonical in seen: continue
        seen.add(canonical); d={'id':len(deals)+1,**d}; deals.append(d)
    data={'version':1,'rules':'draw-one-waste-only-two-redeals-clear-pyramid','method':'seeded constructive legal elimination, rank-and-mirror canonical distinctness','deals':deals}
    content=json.dumps(data,ensure_ascii=False,separators=(',',':'))
    (BASE/'deals.json').write_text(content+'\n')
    (BASE/'deals.js').write_text('/* Generated by generate.py; 50 full legal witnesses. */\nwindow.PYRAMID_DEALS='+content+';\n')
    print('Generated 50 deterministic deals with complete witnesses')
if __name__=='__main__': main()
