#!/usr/bin/env python3
"""Reproducible constructive Spider deals, never a filtered claim about random shuffles.
Only unassigned cards get assigned ranks. Every emitted operation is later replayed
against the final, immutable layout by both the JS engine and independent checker.
"""
import json, random, hashlib
from pathlib import Path
HERE=Path(__file__).resolve().parent

def create(seed):
    rng=random.Random(seed)
    ranks=[None]*104
    initial=[]; cursor=0
    for c in range(10):
        n=6 if c<4 else 5
        initial.append(list(range(cursor,cursor+n))); cursor+=n
    cols=[x[:] for x in initial]
    stock=list(range(54,104)); nextstock=0; witness=[]; taken=0
    deadlines=[rng.randint(a,b) for a,b in [(5,10),(18,24),(31,37),(44,50),(57,63)]]
    def assign(cid,rank):
        nonlocal taken
        assert ranks[cid] is None
        ranks[cid]=rank; taken+=1
    def deal():
        nonlocal nextstock
        assert all(cols) and nextstock<50
        for c in range(10): cols[c].append(stock[nextstock+c])
        nextstock+=10; witness.append({'type':'deal'})
    def move(src,dst,count=1):
        idx=len(cols[src])-count
        witness.append({'type':'move','from':src,'index':idx,'to':dst})
        cols[dst].extend(cols[src][idx:]); del cols[src][idx:]
    for run in range(8):
        # While stock remains keep a card under the new King, so completion cannot
        # leave a forbidden empty tableau before the next row.
        candidates=[c for c in range(10) if len(cols[c]) >= (2 if nextstock<50 else 1)]
        if not candidates:
            deal(); candidates=[c for c in range(10) if len(cols[c])>=2]
        # Choose among the fuller columns, with seeded randomness.
        candidates.sort(key=lambda c:len(cols[c]),reverse=True)
        builder=rng.choice(candidates[:min(4,len(candidates))])
        assign(cols[builder][-1],13)
        empty=[c for c in range(10) if not cols[c]]
        if empty:
            dest=rng.choice(empty); move(builder,dest); builder=dest
        for rank in range(12,0,-1):
            empty=[c for c in range(10) if not cols[c]]
            if empty and len(cols[builder])>13-rank:
                dest=rng.choice(empty); move(builder,dest,13-rank); builder=dest
            candidates=[c for c in range(10) if c!=builder and len(cols[c]) >= (2 if nextstock<50 else 1)]
            due=nextstock<50 and taken>=deadlines[nextstock//10]
            if nextstock<50 and (due or not candidates):
                deal(); assign(cols[builder][-1],rank)
            else:
                if not candidates: raise RuntimeError('Construction exhausted sources')
                # More weight on deep columns without reducing generation to
                # permutations of columns or physical card copy labels.
                src=rng.choices(candidates,weights=[len(cols[c])**1.1 for c in candidates])[0]
                assign(cols[src][-1],rank); move(src,builder)
        assert [ranks[i] for i in cols[builder][-13:]]==list(range(13,0,-1))
        del cols[builder][-13:]
    assert nextstock==50 and not any(cols) and all(r is not None for r in ranks)
    return {'id':seed-701000,'seed':seed,'ranks':ranks,'tableau':initial,'stock':stock,'solution':witness}

def canonical(d):
    # Ignore physical IDs AND permit any simultaneous tableau/stock-column
    # permutation. This is stricter than comparing ordered raw card arrays.
    tracks=[]
    for c,col in enumerate(d['tableau']):
        tracks.append(([d['ranks'][i] for i in col],[d['ranks'][d['stock'][r*10+c]] for r in range(5)]))
    return json.dumps(sorted(tracks),separators=(',',':'))

def main():
    deals=[create(701001+i) for i in range(50)]
    assert len({canonical(d) for d in deals})==50
    data={'format':'spider-one-suit-certified-v1','construction':'seeded legal witness, 54/50 standard layout; not uniformly random','deals':deals}
    raw=json.dumps(data,ensure_ascii=False,separators=(',',':'))
    (HERE/'deals.json').write_text(raw+'\n')
    (HERE/'deals.js').write_text('/* Generated by generate.py; full legal witnesses included. */\n(function(root){const data='+raw+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.SPIDER_DEALS=data;})(typeof globalThis!=="undefined"?globalThis:this);\n')
    print(f'Generated {len(deals)} distinct layouts. Witness actions: {min(len(d["solution"]) for d in deals)}–{max(len(d["solution"]) for d in deals)}. SHA256 {hashlib.sha256(raw.encode()).hexdigest()}')
if __name__=='__main__': main()
