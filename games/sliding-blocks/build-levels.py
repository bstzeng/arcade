#!/usr/bin/env python3
"""Reproducibly regenerate all levels using exhaustive reverse BFS (requires g++)."""
from pathlib import Path
import json, subprocess, tempfile
ROOT=Path(__file__).resolve().parent
names=['初入古道','前鋒移營','東門換防','西營借道','回廊轉陣','長廊易位','兩翼分兵','古城深巷','重圍借路','兵列縱橫','迂迴調將','曲徑突圍','重重關山','孤城破陣','最終出關']
with tempfile.TemporaryDirectory() as tmp:
    binary=Path(tmp)/'generate'
    subprocess.run(['g++','-O3','-std=c++17',str(ROOT/'generate.cpp'),'-o',str(binary)],check=True)
    families=[json.loads(subprocess.check_output([str(binary),str(v),str(12 if v<3 else 13)])) for v in range(1,5)]
levels=[]
for f in families:
    for l in f['levels']:
        l['family']=f['vertical']; levels.append(l)
levels.sort(key=lambda l:(l['optimal'],l['family']))
for i,l in enumerate(levels):
    l['id']=i+1;l['name']=names[min(i*len(names)//50,len(names)-1)]+f' · {i+1:02d}'
    l['tier']=0 if l['optimal']<25 else 1 if l['optimal']<50 else 2 if l['optimal']<85 else 3 if l['optimal']<115 else 4
out={'version':1,'rules':'4x5, target 2x2 reaches (1,3); one straight slide of any positive length = one move','proof':'Exhaustive reverse multi-source BFS from every legal goal arrangement; interchangeable rectangles canonicalized by shape. Every saved distance is globally optimal.','families':[{k:v for k,v in f.items() if k!='levels'} for f in families],'levels':levels}
(ROOT/'levels.json').write_text(json.dumps(out,ensure_ascii=False,separators=(',',':'))+'\n')
(ROOT/'levels.js').write_text('/* Generated by build-levels.py. See README.md for BFS proof and replay verification. */\nwindow.SLIDING_LEVEL_DATA = '+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
print(f'Generated {len(levels)} levels, optimal moves {levels[0]["optimal"]}–{levels[-1]["optimal"]}')
